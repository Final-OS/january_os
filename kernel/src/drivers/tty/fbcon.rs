//! 简单 Framebuffer 控制台
//!
//! 直接在 framebuffer 上绘制文字，无需动态内存分配

use core::sync::atomic::{AtomicU64, AtomicU32, AtomicUsize, Ordering};
use core::fmt::{self, Write};
use crate::sync::SpinLock;

// ============================================================================
// 8x16 位图字体 (基本 ASCII)
// ============================================================================

const FONT_WIDTH: usize = 8;
const FONT_HEIGHT: usize = 16;

/// 获取字符的字形数据
fn get_glyph(ch: char) -> &'static [u8; FONT_HEIGHT] {
    let idx = ch as usize;
    if idx < 128 {
        &BASIC_FONT[idx]
    } else {
        &BASIC_FONT[0] // 未知字符显示为方块
    }
}

// ============================================================================
// 像素格式
// ============================================================================

/// 像素格式类型
#[repr(u32)]
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum PixelFormat {
    /// RGB 格式 (R在低字节): 0x00RRGGBB
    Rgb = 0,
    /// BGR 格式 (B在低字节): 0x00BBGGRR - 最常见
    Bgr = 1,
    /// 其他格式
    Other = 2,
}

impl From<u32> for PixelFormat {
    fn from(v: u32) -> Self {
        match v {
            0 => PixelFormat::Rgb,
            1 => PixelFormat::Bgr,
            _ => PixelFormat::Other,
        }
    }
}

// ============================================================================
// Framebuffer 状态
// ============================================================================

/// Framebuffer 地址
static FB_ADDR: AtomicU64 = AtomicU64::new(0);
/// Framebuffer 宽度 (像素)
static FB_WIDTH: AtomicU32 = AtomicU32::new(0);
/// Framebuffer 高度 (像素)
static FB_HEIGHT: AtomicU32 = AtomicU32::new(0);
/// Framebuffer 步幅 (像素/行，即 pixels per scanline)
static FB_STRIDE: AtomicU32 = AtomicU32::new(0);
/// 像素格式
static FB_FORMAT: AtomicU32 = AtomicU32::new(1); // 默认 BGR

/// 控制台列数
static COLS: AtomicUsize = AtomicUsize::new(0);
/// 控制台行数
static ROWS: AtomicUsize = AtomicUsize::new(0);

/// 光标位置
static CURSOR_X: AtomicUsize = AtomicUsize::new(0);
static CURSOR_Y: AtomicUsize = AtomicUsize::new(0);

/// 基础颜色 (RGB 格式，会在输出时转换)
const DEFAULT_FG_COLOR: u32 = 0x00CCCCCC; // 浅灰前景
const DEFAULT_BG_COLOR: u32 = 0x00000000; // 黑色背景

/// 当前前景色 (RGB)
static FG_COLOR: AtomicU32 = AtomicU32::new(DEFAULT_FG_COLOR);
/// 当前背景色 (RGB)
static BG_COLOR: AtomicU32 = AtomicU32::new(DEFAULT_BG_COLOR);

/// 设置前景色
pub fn set_fg_color(rgb: u32) {
    FG_COLOR.store(rgb, Ordering::Relaxed);
}

/// 设置背景色
pub fn set_bg_color(rgb: u32) {
    BG_COLOR.store(rgb, Ordering::Relaxed);
}

/// 获取当前颜色
pub fn get_colors() -> (u32, u32) {
    (FG_COLOR.load(Ordering::Relaxed), BG_COLOR.load(Ordering::Relaxed))
}

/// 设置光标位置
pub fn set_cursor_pos(x: usize, y: usize) {
    let cols = COLS.load(Ordering::Relaxed);
    let rows = ROWS.load(Ordering::Relaxed);
    if x < cols && y < rows {
        CURSOR_X.store(x, Ordering::Relaxed);
        CURSOR_Y.store(y, Ordering::Relaxed);
    }
}

/// 获取光标位置
pub fn get_cursor_pos() -> (usize, usize) {
    (CURSOR_X.load(Ordering::Relaxed), CURSOR_Y.load(Ordering::Relaxed))
}

/// 获取屏幕尺寸 (cols, rows)
pub fn get_screen_size() -> (usize, usize) {
    (COLS.load(Ordering::Relaxed), ROWS.load(Ordering::Relaxed))
}

/// 根据像素格式转换颜色
fn convert_color(rgb: u32) -> u32 {
    let format = PixelFormat::from(FB_FORMAT.load(Ordering::Relaxed));
    match format {
        PixelFormat::Rgb => rgb,
        PixelFormat::Bgr | PixelFormat::Other => {
            // RGB -> BGR: 交换 R 和 B
            let r = (rgb >> 16) & 0xFF;
            let g = (rgb >> 8) & 0xFF;
            let b = rgb & 0xFF;
            (b << 16) | (g << 8) | r
        }
    }
}

// ============================================================================
// 初始化
// ============================================================================

/// 获取 Framebuffer 信息 (width, height, stride, format)
pub fn info() -> (u32, u32, u32, u32) {
    (
        FB_WIDTH.load(Ordering::Relaxed),
        FB_HEIGHT.load(Ordering::Relaxed),
        FB_STRIDE.load(Ordering::Relaxed),
        FB_FORMAT.load(Ordering::Relaxed),
    )
}

/// 初始化 framebuffer 控制台
/// 
/// # 参数
/// - `addr`: Framebuffer 物理地址
/// - `width`: 宽度（像素）
/// - `height`: 高度（像素）
/// - `stride`: 每行字节数
/// - `pixel_format`: 像素格式 (0=RGB, 1=BGR)
pub fn init(addr: u64, width: u32, height: u32, stride: u32, pixel_format: u32) {
    if addr == 0 || width == 0 || height == 0 {
        return;
    }
    
    FB_ADDR.store(addr, Ordering::SeqCst);
    FB_WIDTH.store(width, Ordering::SeqCst);
    FB_HEIGHT.store(height, Ordering::SeqCst);
    FB_STRIDE.store(stride, Ordering::SeqCst);
    FB_FORMAT.store(pixel_format, Ordering::SeqCst);
    
    let cols = width as usize / FONT_WIDTH;
    let rows = height as usize / FONT_HEIGHT;
    COLS.store(cols, Ordering::SeqCst);
    ROWS.store(rows, Ordering::SeqCst);
    
    // 直接使用传入参数清屏（避免原子变量加载问题）
    let bg = if pixel_format == 0 { DEFAULT_BG_COLOR } else {
        // BGR 格式
        let r = (DEFAULT_BG_COLOR >> 16) & 0xFF;
        let g = (DEFAULT_BG_COLOR >> 8) & 0xFF;
        let b = DEFAULT_BG_COLOR & 0xFF;
        (b << 16) | (g << 8) | r
    };
    
    let fb = addr as *mut u32;
    let w = width as usize;
    let h = height as usize;
    let s = stride as usize;
    
    unsafe {
        for y in 0..h {
            for x in 0..w {
                *fb.add(y * s + x) = bg;
            }
        }
    }
    
    CURSOR_X.store(0, Ordering::Relaxed);
    CURSOR_Y.store(0, Ordering::Relaxed);
}

/// 检查是否已初始化
pub fn is_initialized() -> bool {
    FB_ADDR.load(Ordering::Relaxed) != 0
}

/// 清屏
pub fn clear_screen() {
    let addr = FB_ADDR.load(Ordering::Relaxed);
    if addr == 0 {
        return;
    }
    
    let width = FB_WIDTH.load(Ordering::Relaxed) as usize;
    let height = FB_HEIGHT.load(Ordering::Relaxed) as usize;
    let stride = FB_STRIDE.load(Ordering::Relaxed) as usize; // 像素数，不需要除以4
    let bg = convert_color(BG_COLOR.load(Ordering::Relaxed));
    
    let fb = addr as *mut u32;
    
    for y in 0..height {
        for x in 0..width {
            unsafe {
                *fb.add(y * stride + x) = bg;
            }
        }
    }
    
    CURSOR_X.store(0, Ordering::Relaxed);
    CURSOR_Y.store(0, Ordering::Relaxed);
}

// ============================================================================
// 字符输出
// ============================================================================

/// 在指定位置绘制字符
fn draw_char(col: usize, row: usize, ch: char, fg_rgb: u32, bg_rgb: u32) {
    let addr = FB_ADDR.load(Ordering::Relaxed);
    if addr == 0 {
        return;
    }
    
    let stride = FB_STRIDE.load(Ordering::Relaxed) as usize; // 像素数
    let fb = addr as *mut u32;
    
    // 转换颜色格式
    let fg = convert_color(fg_rgb);
    let bg = convert_color(bg_rgb);
    
    let x = col * FONT_WIDTH;
    let y = row * FONT_HEIGHT;
    
    let glyph = get_glyph(ch);
    
    for dy in 0..FONT_HEIGHT {
        for dx in 0..FONT_WIDTH {
            let pixel_x = x + dx;
            let pixel_y = y + dy;
            let offset = pixel_y * stride + pixel_x;
            
            let bit = (glyph[dy] >> (FONT_WIDTH - 1 - dx)) & 1;
            let color = if bit != 0 { fg } else { bg };
            
            unsafe {
                *fb.add(offset) = color;
            }
        }
    }
}

/// 滚动屏幕
fn scroll_up() {
    let addr = FB_ADDR.load(Ordering::Relaxed);
    if addr == 0 {
        return;
    }
    
    let width = FB_WIDTH.load(Ordering::Relaxed) as usize;
    let height = FB_HEIGHT.load(Ordering::Relaxed) as usize;
    let stride = FB_STRIDE.load(Ordering::Relaxed) as usize; // 像素数
    let bg = convert_color(BG_COLOR.load(Ordering::Relaxed));
    
    let fb = addr as *mut u32;
    let line_height = FONT_HEIGHT;
    
    // 向上移动所有行
    for y in 0..(height - line_height) {
        for x in 0..width {
            unsafe {
                let src = *fb.add((y + line_height) * stride + x);
                *fb.add(y * stride + x) = src;
            }
        }
    }
    
    // 清除最后一行
    for y in (height - line_height)..height {
        for x in 0..width {
            unsafe {
                *fb.add(y * stride + x) = bg;
            }
        }
    }
}

/// 输出一个字符
pub fn put_char(ch: char) {
    if !is_initialized() {
        return;
    }
    
    let cols = COLS.load(Ordering::Relaxed);
    let rows = ROWS.load(Ordering::Relaxed);
    let mut x = CURSOR_X.load(Ordering::Relaxed);
    let mut y = CURSOR_Y.load(Ordering::Relaxed);
    
    match ch {
        '\n' => {
            x = 0;
            y += 1;
        }
        '\r' => {
            x = 0;
        }
        '\t' => {
            x = (x + 8) & !7;
            if x >= cols {
                x = 0;
                y += 1;
            }
        }
        '\x08' => { // Backspace
            if x > 0 {
                x -= 1;
                draw_char(x, y, ' ', FG_COLOR.load(Ordering::Relaxed), BG_COLOR.load(Ordering::Relaxed));
            }
        }
        ch if ch >= ' ' => {
            draw_char(x, y, ch, FG_COLOR.load(Ordering::Relaxed), BG_COLOR.load(Ordering::Relaxed));
            x += 1;
            if x >= cols {
                x = 0;
                y += 1;
            }
        }
        _ => {}
    }
    
    // 滚动
    if y >= rows {
        scroll_up();
        y = rows - 1;
    }
    
    CURSOR_X.store(x, Ordering::Relaxed);
    CURSOR_Y.store(y, Ordering::Relaxed);
}

/// 输出字符串
pub fn put_str(s: &str) {
    for ch in s.chars() {
        put_char(ch);
    }
}

// ============================================================================
// fmt::Write 实现
// ============================================================================

/// Framebuffer 控制台写入器
pub struct FbConsoleWriter;

impl Write for FbConsoleWriter {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        put_str(s);
        Ok(())
    }
}

